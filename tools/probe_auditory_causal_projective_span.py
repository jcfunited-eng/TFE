"""Falsify or advance an exact causal projective hearing profile.

The candidate is the smallest exact physical basin suggested by linear
acoustic gain and superposition.  A causally authenticated THING owns the
positive rational cone generated by its complete bilateral full-field
trajectories.  This probe first tests the larger rational linear span.  If a
query is outside that span, it is necessarily outside the positive cone.

No distance, score, threshold, nearest relation, label-derived feature,
alignment, interpolation, or whole-root equality is used.  A non-membership
result carries a finite-field rank witness.  Nonzero rank modulo a prime
proves nonzero rational rank after denominator clearing.
"""

