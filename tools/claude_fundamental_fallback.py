def get_fallback_fundamentals(ticker: str) -> Optional[Dict[str, Any]]:
    """Return known fundamentals for a ticker, or None if not in the lookup."""
    data = KNOWN_FUNDAMENTALS.get(ticker.upper().strip())
    if data is None:
        return None

    return {
        "status": "CLAUDE_FALLBACK",
        "reason": "Data from Claude knowledge base — public SEC filings",
        "sector": data["sector"],
        "metrics": {
            "market_cap": data["market_cap"],
            "revenues": data["revenues"],
            "gross_profit": data["gross_profit"],
            "operating_cash_flow": data["operating_cash_flow"],
            "free_cash_flow": data["free_cash_flow"],
            "current_ratio": data["current_ratio"],
            "gross_margin": data["gross_margin"],
        },
    }
