#[derive(Debug, Clone, PartialEq)]
pub struct GapJunction {
    pub comp_a: usize,
    pub comp_b: usize,
    pub conductance: f64, // [S]
}

#[derive(Debug, Clone, PartialEq)]
pub struct ChemicalSynapse {
    pub pre_comp: usize,
    pub post_comp: usize,
    pub peak_conductance: f64, // [S]
    pub current_conductance: f64, // [S]
    pub decay_tau: f64,        // [s]
    pub reversal: f64,         // [V]
}

#[derive(Debug, Clone, PartialEq)]
pub struct RecurrentPersistenceNetwork {
    pub compartments: Vec<NeuronalCompartment>,
    pub gap_junctions: Vec<GapJunction>,
    pub recurrent_synapses: Vec<ChemicalSynapse>,
    pub need_coupling: BodilyNeedCoupling,
    pub need_target_compartment: usize,
}

impl RecurrentPersistenceNetwork {
    pub fn new(
        num_compartments: usize,
        need_coupling: BodilyNeedCoupling,
        need_target_compartment: usize,
    ) -> Result<Self, ConstitutiveError> {
        if num_compartments == 0 {
            return Err(ConstitutiveError::InvalidDomain(
                "num_compartments must be >= 1".to_string(),
            ));
        }
        if need_target_compartment >= num_compartments {
            return Err(ConstitutiveError::InvalidDomain(
                "need_target_compartment out of bounds".to_string(),
            ));
        }

        let mut compartments = Vec::with_capacity(num_compartments);
        for i in 0..num_compartments {
            compartments.push(NeuronalCompartment::new(
                i,
                DEFAULT_LEAK_REVERSAL,
                DEFAULT_MEMBRANE_CAPACITANCE,
                DEFAULT_LEAK_CONDUCTANCE,
                DEFAULT_LEAK_REVERSAL,
                DEFAULT_ACTION_THRESHOLD,
                DEFAULT_RESET_VOLTAGE,
            )?);
        }

        Ok(Self {
            compartments,
            gap_junctions: Vec::new(),
            recurrent_synapses: Vec::new(),
            need_coupling,
            need_target_compartment,
        })
    }

    pub fn add_gap_junction(
        &mut self,
        comp_a: usize,
        comp_b: usize,
        conductance: f64,
    ) -> Result<(), ConstitutiveError> {
        if comp_a >= self.compartments.len() || comp_b >= self.compartments.len() {
            return Err(ConstitutiveError::InvalidDomain("compartment index out of bounds".to_string()));
        }
        if conductance < 0.0 || !conductance.is_finite() {
            return Err(ConstitutiveError::InvalidDomain("conductance must be non-negative".to_string()));
        }
        self.gap_junctions.push(GapJunction { comp_a, comp_b, conductance });
        Ok(())
    }

    pub fn add_synapse(
        &mut self,
        pre_comp: usize,
        post_comp: usize,
        peak_conductance: f64,
        decay_tau: f64,
        reversal: f64,
    ) -> Result<(), ConstitutiveError> {
        if pre_comp >= self.compartments.len() || post_comp >= self.compartments.len() {
            return Err(ConstitutiveError::InvalidDomain("compartment index out of bounds".to_string()));
        }
        if peak_conductance < 0.0 || !peak_conductance.is_finite() {
            return Err(ConstitutiveError::InvalidDomain("peak_conductance must be non-negative".to_string()));
        }
        if decay_tau <= 0.0 || !decay_tau.is_finite() {
            return Err(ConstitutiveError::InvalidDomain("decay_tau must be strictly positive".to_string()));
        }
        self.recurrent_synapses.push(ChemicalSynapse {
            pre_comp,
            post_comp,
            peak_conductance,
            current_conductance: 0.0,
            decay_tau,
            reversal,
        });
        Ok(())
    }

    /// Advances the recurrent network by physical time dt [s].
    pub fn step(
        &mut self,
        dt: f64,
        external_distractor_currents: &[f64],
    ) -> Result<(), ConstitutiveError> {
        let n = self.compartments.len();
        let mut currents = vec![0.0f64; n];

        // 1. Need afference driving target compartment
        let v_target = self.compartments[self.need_target_compartment].voltage();
        let i_need = self.need_coupling.compute_current(v_target);
        currents[self.need_target_compartment] += i_need;

        // 2. External distractor currents (if any)
        for (i, &dist_i) in external_distractor_currents.iter().enumerate().take(n) {
            currents[i] += dist_i;
        }

        // 3. Gap junctions: I_gap,a->b = g * (V_a - V_b) (equal and opposite)
        for gap in &self.gap_junctions {
            let v_a = self.compartments[gap.comp_a].voltage();
            let v_b = self.compartments[gap.comp_b].voltage();
            let i_transfer = gap.conductance * (v_a - v_b);
            currents[gap.comp_a] -= i_transfer;
            currents[gap.comp_b] += i_transfer;
        }

        // 4. Update chemical synapse conductances and compute postsynaptic currents
        for syn in &mut self.recurrent_synapses {
            // If presynaptic neuron spiked in previous step, trigger quantal conductance jump
            if self.compartments[syn.pre_comp].is_spiking {
                syn.current_conductance += syn.peak_conductance;
            }
            // Exponential decay of synaptic conductance: dg/dt = -g / tau
            let decay_factor = (-dt / syn.decay_tau).exp();
            syn.current_conductance *= decay_factor;

            // Inward postsynaptic current: I = -g * (V_post - E_rev)
            let v_post = self.compartments[syn.post_comp].voltage();
            let i_syn = -syn.current_conductance * (v_post - syn.reversal);
            currents[syn.post_comp] += i_syn;
        }

        // 5. Integrate leak and synaptic currents per compartment
        for (i, comp) in self.compartments.iter_mut().enumerate() {
            comp.step_leak(dt)?;
            comp.inject_current(currents[i], dt)?;
        }

        Ok(())
    }

    /// Total stored electrical energy in network [J].
    pub fn total_stored_energy(&self) -> f64 {
        self.compartments.iter().map(|c| c.stored_energy()).sum()
    }
}

