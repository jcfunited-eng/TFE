/// Lawful receptor-gated bodily need mechanism (§9).
/// Translates systemic metabolic deficit into depolarizing neuronal drive
/// via finite chemical kinetics: R + Need <=> A_need.
/// Conserves signaling molecule population with finite systemic reservoir.
#[derive(Debug, Clone, PartialEq)]
pub struct BodilyNeedCoupling {
    pub receptors: ReceptorKineticsState,
    pub max_conductance: f64,
    pub reversal_potential: f64,
    pub systemic_reservoir: f64, // Finite systemic bath [mol]
}

impl BodilyNeedCoupling {
    pub fn new(
        r_total_zmol: f64,
        cleft_vol_attoliter: f64,
        k_on: f64,
        k_off: f64,
        max_conductance: f64,
        reversal_potential: f64,
        initial_systemic_reservoir_pmol: f64,
    ) -> Result<Self, ConstitutiveError> {
        let receptors = ReceptorKineticsState::new(
            r_total_zmol * 1.0e-21,
            0.0,
            0.0,
            0.0,
            cleft_vol_attoliter * 1.0e-18,
            0.0,
            k_on,
            k_off,
            0.0,
            1.0,
        )?;
        Ok(Self {
            receptors,
            max_conductance,
            reversal_potential,
            systemic_reservoir: initial_systemic_reservoir_pmol * 1.0e-12,
        })
    }

    /// Updates extracellular metabolic deficit concentration and steps binding kinetics over dt [s].
    pub fn update_need(
        &mut self,
        deficit_concentration_mol_m3: f64,
        dt: f64,
    ) -> Result<(), ConstitutiveError> {
        if !deficit_concentration_mol_m3.is_finite() || deficit_concentration_mol_m3 < 0.0 {
            return Err(ConstitutiveError::InvalidDomain(
                "deficit_concentration_mol_m3 must be non-negative and finite".to_string(),
            ));
        }
        // Target free transmitter in cleft is proportional to systemic deficit concentration
        let target_t = deficit_concentration_mol_m3 * self.receptors.v_cleft;
        let delta_t = target_t - self.receptors.t_free;
        if delta_t.abs() > 1e-25 {
            self.receptors.exchange_transmitter(delta_t, &mut self.systemic_reservoir)?;
        }
        self.receptors.step_kinetics(dt)?;

        // Vascular/enzymatic clearance: excess dissociated transmitter equilibrates with systemic circulation
        let excess_t = self.receptors.t_free - target_t;
        if excess_t > 1e-25 {
            self.receptors.exchange_transmitter(-excess_t, &mut self.systemic_reservoir)?;
        }

        Ok(())
    }

    /// Computes inward depolarizing need current I_need = g_need * (V - E_need) [A].
    #[inline]
    pub fn compute_current(&self, post_voltage: f64) -> f64 {
        let r_tot = self.receptors.total_receptors();
        if r_tot <= 0.0 {
            return 0.0;
        }
        let occupancy = (self.receptors.a_active / r_tot).clamp(0.0, 1.0);
        let g_need = self.max_conductance * occupancy;
        // Inward depolarizing current is positive inward: I = -g * (V - E)
        -g_need * (post_voltage - self.reversal_potential)
    }
}

