#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SensoryChannelType {
    TactileContactForceNewtons,   // [N]
    RetinalBearingRadians,        // [rad]
    SubtendedAngularSizeRadians,  // [rad]
    ProprioceptiveAngleRadians,   // [rad]
}

impl SensoryChannelType {
    pub fn to_u8(self) -> u8 {
        match self {
            SensoryChannelType::TactileContactForceNewtons => 0,
            SensoryChannelType::RetinalBearingRadians => 1,
            SensoryChannelType::SubtendedAngularSizeRadians => 2,
            SensoryChannelType::ProprioceptiveAngleRadians => 3,
        }
    }

    pub fn from_u8(val: u8) -> Result<Self, ConstitutiveError> {
        match val {
            0 => Ok(SensoryChannelType::TactileContactForceNewtons),
            1 => Ok(SensoryChannelType::RetinalBearingRadians),
            2 => Ok(SensoryChannelType::SubtendedAngularSizeRadians),
            3 => Ok(SensoryChannelType::ProprioceptiveAngleRadians),
            _ => Err(ConstitutiveError::CorruptData(format!("Unknown channel tag {}", val))),
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct ChannelPredictionResult {
    pub channel: SensoryChannelType,
    pub predicted_value: f64,
    pub mismatch: MismatchResult,
}

#[derive(Debug, Clone, PartialEq)]
pub enum MismatchResult {
    Available { error: f64 },
    Unavailable { reason: String },
}

#[derive(Debug, Clone, PartialEq)]
pub struct ForwardSynapticContact {
    pub contact_id: usize,
    pub input_neuron_id: usize,
    pub weight: f64, // Predictive transmission gain in channel-specific physical units
    pub is_ablated: bool,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ChannelPredictor {
    pub channel: SensoryChannelType,
    pub baseline_expectation: f64,
    pub contacts: Vec<ForwardSynapticContact>,
}

impl ChannelPredictor {
    pub fn new(channel: SensoryChannelType, baseline_expectation: f64) -> Self {
        Self {
            channel,
            baseline_expectation,
            contacts: Vec::new(),
        }
    }

    pub fn add_contact(&mut self, input_neuron_id: usize, weight: f64) {
        let contact_id = self.contacts.len();
        self.contacts.push(ForwardSynapticContact {
            contact_id,
            input_neuron_id,
            weight,
            is_ablated: false,
        });
    }

    /// Evaluates forward internal model prediction BEFORE outcome:
    ///   s_hat = baseline + sum_j W_j * a_j
    pub fn evaluate_prediction(&self, input_activations: &[f64]) -> f64 {
        let mut s_hat = self.baseline_expectation;
        for c in &self.contacts {
            if !c.is_ablated && c.input_neuron_id < input_activations.len() {
                s_hat += c.weight * input_activations[c.input_neuron_id];
            }
        }
        s_hat
    }

    /// Compares predicted expectation with actual arriving observation:
    ///   epsilon = s_actual - s_hat
    /// If evidence is unavailable, returns Unavailable without zeroing (§4).
    pub fn evaluate_mismatch(
        &self,
        predicted: f64,
        actual: &SensedValue<f64>,
    ) -> ChannelPredictionResult {
        let mismatch = match actual {
            SensedValue::Available(s_act) => MismatchResult::Available {
                error: *s_act - predicted,
            },
            SensedValue::Unavailable { reason } => MismatchResult::Unavailable {
                reason: reason.clone(),
            },
        };

        ChannelPredictionResult {
            channel: self.channel,
            predicted_value: predicted,
            mismatch,
        }
    }

    /// C02 Targeted retention ablation: ablates specific contact.
    pub fn ablate_contact(&mut self, contact_id: usize) -> Result<(), ConstitutiveError> {
        if let Some(c) = self.contacts.iter_mut().find(|c| c.contact_id == contact_id) {
            c.is_ablated = true;
            Ok(())
        } else {
            Err(ConstitutiveError::InvalidDomain("contact_id not found".to_string()))
        }
    }

    /// Restores ablated contact.
    pub fn restore_contact(&mut self, contact_id: usize) -> Result<(), ConstitutiveError> {
        if let Some(c) = self.contacts.iter_mut().find(|c| c.contact_id == contact_id) {
            c.is_ablated = false;
            Ok(())
        } else {
            Err(ConstitutiveError::InvalidDomain("contact_id not found".to_string()))
        }
    }
}

