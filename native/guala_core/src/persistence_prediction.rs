#[derive(Debug, Clone, PartialEq)]
pub struct PersistenceAndPredictionHarness {
    pub network: RecurrentPersistenceNetwork,
    pub predictors: Vec<ChannelPredictor>,
}

impl PersistenceAndPredictionHarness {
    pub fn new(
        network: RecurrentPersistenceNetwork,
        predictors: Vec<ChannelPredictor>,
    ) -> Self {
        Self { network, predictors }
    }

    /// Extracts normalized firing / activation levels across network compartments.
    pub fn get_activations(&self) -> Vec<f64> {
        self.network
            .compartments
            .iter()
            .map(|c| {
                if c.is_spiking {
                    1.0
                } else {
                    let v = c.voltage();
                    let v_rest = c.leak_reversal;
                    let v_thresh = c.threshold;
                    if v <= v_rest {
                        0.0
                    } else {
                        ((v - v_rest) / (v_thresh - v_rest)).clamp(0.0, 1.0)
                    }
                }
            })
            .collect()
    }

    /// Computes forward channel-wise predictions BEFORE outcome arrives.
    pub fn predict_channels(&self) -> Vec<(SensoryChannelType, f64)> {
        let acts = self.get_activations();
        self.predictors
            .iter()
            .map(|p| (p.channel, p.evaluate_prediction(&acts)))
            .collect()
    }

    /// Compares pre-computed channel predictions with arriving actual sensory inputs.
    pub fn evaluate_all_mismatches(
        &self,
        predictions: &[(SensoryChannelType, f64)],
        observations: &[(SensoryChannelType, SensedValue<f64>)],
    ) -> Vec<ChannelPredictionResult> {
        let default_unavail = SensedValue::Unavailable {
            reason: "Channel not observed in sensorium frame".to_string(),
        };
        let mut results = Vec::with_capacity(predictions.len());
        for (channel, pred_val) in predictions {
            if let Some(predictor) = self.predictors.iter().find(|p| p.channel == *channel) {
                let obs = observations
                    .iter()
                    .find(|(ch, _)| ch == channel)
                    .map(|(_, val)| val)
                    .unwrap_or(&default_unavail);
                results.push(predictor.evaluate_mismatch(*pred_val, obs));
            }
        }
        results
    }

    /// Serializes entire harness state into byte array for cold restart (§8).
    pub fn serialize_continuation(&self) -> Vec<u8> {
        let mut buf = Vec::new();
        buf.extend_from_slice(CONTINUATION_MAGIC);

        // Network compartments
        let num_comps = self.network.compartments.len() as u32;
        buf.extend_from_slice(&num_comps.to_le_bytes());
        for c in &self.network.compartments {
            buf.extend_from_slice(&(c.id as u32).to_le_bytes());
            buf.extend_from_slice(&c.carrier.q_membrane.to_le_bytes());
            buf.extend_from_slice(&c.carrier.c_mem.to_le_bytes());
            buf.extend_from_slice(&c.carrier.remainder.to_le_bytes());
            buf.extend_from_slice(&c.carrier.source_reservoir.to_le_bytes());
            buf.extend_from_slice(&c.carrier.dest_reservoir.to_le_bytes());
            buf.extend_from_slice(&c.leak_conductance.to_le_bytes());
            buf.extend_from_slice(&c.leak_reversal.to_le_bytes());
            buf.extend_from_slice(&c.threshold.to_le_bytes());
            buf.extend_from_slice(&c.reset_voltage.to_le_bytes());
            buf.push(if c.is_spiking { 1 } else { 0 });
        }

        // Need coupling
        let r = &self.network.need_coupling.receptors;
        buf.extend_from_slice(&r.r_free.to_le_bytes());
        buf.extend_from_slice(&r.a_active.to_le_bytes());
        buf.extend_from_slice(&r.d_inact.to_le_bytes());
        buf.extend_from_slice(&r.t_free.to_le_bytes());
        buf.extend_from_slice(&r.v_cleft.to_le_bytes());
        buf.extend_from_slice(&r.integrated_exposure.to_le_bytes());
        buf.extend_from_slice(&r.k_on.to_le_bytes());
        buf.extend_from_slice(&r.k_off.to_le_bytes());
        buf.extend_from_slice(&r.k_inact.to_le_bytes());
        buf.extend_from_slice(&r.k_rec.to_le_bytes());
        buf.extend_from_slice(&self.network.need_coupling.max_conductance.to_le_bytes());
        buf.extend_from_slice(&self.network.need_coupling.reversal_potential.to_le_bytes());
        buf.extend_from_slice(&self.network.need_coupling.systemic_reservoir.to_le_bytes());
        buf.extend_from_slice(&(self.network.need_target_compartment as u32).to_le_bytes());

        // Simple Adler-32 / CRC checksum over the payload
        let checksum = crc32_simple(&buf[8..]);
        buf.extend_from_slice(&checksum.to_le_bytes());

        buf
    }

    /// Deserializes harness state with exact verification (§8).
    pub fn deserialize_continuation(
        bytes: &[u8],
        base_predictors: Vec<ChannelPredictor>,
        gap_junctions: Vec<GapJunction>,
        synapses: Vec<ChemicalSynapse>,
    ) -> Result<Self, ConstitutiveError> {
        if bytes.len() < 16 {
            return Err(ConstitutiveError::TruncatedData {
                expected: 16,
                actual: bytes.len(),
            });
        }
        if &bytes[0..8] != CONTINUATION_MAGIC {
            return Err(ConstitutiveError::CorruptData("Invalid magic header".to_string()));
        }

        let payload_len = bytes.len() - 4;
        let stored_crc = u32::from_le_bytes(bytes[payload_len..].try_into().unwrap());
        let computed_crc = crc32_simple(&bytes[8..payload_len]);
        if stored_crc != computed_crc {
            return Err(ConstitutiveError::InvalidChecksum {
                expected: stored_crc,
                computed: computed_crc,
            });
        }

        let mut offset = 8;
        let num_comps = u32::from_le_bytes(bytes[offset..offset + 4].try_into().unwrap()) as usize;
        offset += 4;

        let mut compartments = Vec::with_capacity(num_comps);
        for _ in 0..num_comps {
            let id = u32::from_le_bytes(bytes[offset..offset + 4].try_into().unwrap()) as usize;
            offset += 4;
            let q_membrane = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
            offset += 8;
            let c_mem = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
            offset += 8;
            let remainder = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
            offset += 8;
            let source_res = u64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
            offset += 8;
            let dest_res = u64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
            offset += 8;
            let leak_g = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
            offset += 8;
            let leak_e = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
            offset += 8;
            let thresh = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
            offset += 8;
            let reset_v = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
            offset += 8;
            let is_spk = bytes[offset] == 1;
            offset += 1;

            let carrier = ChargeCarrierState::new(q_membrane, c_mem, remainder, source_res, dest_res)?;
            compartments.push(NeuronalCompartment {
                id,
                carrier,
                leak_conductance: leak_g,
                leak_reversal: leak_e,
                threshold: thresh,
                reset_voltage: reset_v,
                is_spiking: is_spk,
            });
        }

        // Need coupling
        let r_free = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let a_active = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let d_inact = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let t_free = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let v_cleft = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let integrated_exposure = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let k_on = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let k_off = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let k_inact = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let k_rec = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let max_g = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let rev_p = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let sys_res = f64::from_le_bytes(bytes[offset..offset + 8].try_into().unwrap());
        offset += 8;
        let target_comp = u32::from_le_bytes(bytes[offset..offset + 4].try_into().unwrap()) as usize;

        let receptors = ReceptorKineticsState::new(
            r_free,
            a_active,
            d_inact,
            t_free,
            v_cleft,
            integrated_exposure,
            k_on,
            k_off,
            k_inact,
            k_rec,
        )?;

        let need_coupling = BodilyNeedCoupling {
            receptors,
            max_conductance: max_g,
            reversal_potential: rev_p,
            systemic_reservoir: sys_res,
        };

        let network = RecurrentPersistenceNetwork {
            compartments,
            gap_junctions,
            recurrent_synapses: synapses,
            need_coupling,
            need_target_compartment: target_comp,
        };

        Ok(Self {
            network,
            predictors: base_predictors,
        })
    }
}

#[inline]
fn crc32_simple(data: &[u8]) -> u32 {
    let mut crc: u32 = 0xFFFF_FFFF;
    for &b in data {
        crc ^= b as u32;
        for _ in 0..8 {
            if crc & 1 != 0 {
                crc = (crc >> 1) ^ 0xEDB8_8320;
            } else {
                crc >>= 1;
            }
        }
    }
    !crc
}

