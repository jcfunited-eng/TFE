    fn create_test_network() -> RecurrentPersistenceNetwork {
        // Need receptor: total 50 zmol, max conductance 25 nS, reversal 0.0 V (depolarizing)
        // Finite systemic reservoir: 1000 pmol
        let need_coupling = BodilyNeedCoupling::new(
            50.0,    // 50 zmol total receptors
            1.0,     // 1 attoliter
            1.0e6,   // k_on
            50.0,    // k_off (fast dissociation on relief)
            25.0e-9, // 25 nS max conductance
            0.0,     // 0 mV depolarizing reversal
            1000.0,  // 1000 pmol initial systemic reservoir
        ).unwrap();

        // 3-compartment recurrent network:
        // Compartment 0: Need target & excitatory driver
        // Compartment 1: Recurrent persistence interneuron
        // Compartment 2: Distractor / sensory input recipient
        let mut net = RecurrentPersistenceNetwork::new(3, need_coupling, 0).unwrap();

        // Recurrent excitation between 0 and 1: peak conductance 8 nS, tau 3 ms
        net.add_synapse(0, 1, 8.0e-9, 0.003, DEFAULT_EXCITATORY_REVERSAL).unwrap();
        net.add_synapse(1, 0, 8.0e-9, 0.003, DEFAULT_EXCITATORY_REVERSAL).unwrap();

        // Weak gap junction between 1 and 2
        net.add_gap_junction(1, 2, 2.0e-9).unwrap();

        net
    }

    #[test]
    fn test_recurrent_active_state_persistence_under_distraction() {
        let mut net = create_test_network();
        let dt = 0.001; // 1 ms time step

        // 1. Quiescent initial state (no need deficit)
        assert_eq!(net.need_coupling.receptors.a_active, 0.0);
        for _ in 0..50 {
            net.step(dt, &[0.0, 0.0, 0.0]).unwrap();
        }
        assert!(!net.compartments[0].is_spiking, "Network must remain quiescent at rest");
        assert!(!net.compartments[1].is_spiking, "Interneuron must remain quiescent");

        // 2. High metabolic deficit arrives: drives Compartment 0 into persistent attractor
        net.need_coupling.update_need(5.0, dt).unwrap(); // 5 mol/m^3 deficit
        assert!(net.need_coupling.receptors.a_active > 0.0);

        // Run until persistent firing is established
        let mut spikes_comp0 = 0;
        for _ in 0..100 {
            net.step(dt, &[0.0, 0.0, 0.0]).unwrap();
            if net.compartments[0].is_spiking {
                spikes_comp0 += 1;
            }
        }
        assert!(spikes_comp0 > 0, "Need drive must induce spiking in target compartment");

        // 3. Apply external distractor current to Compartment 2 for 50 ms
        let distractor_current = 0.5e-9; // 0.5 nA distractor
        let mut distractor_spikes = 0;
        for _ in 0..50 {
            net.step(dt, &[0.0, 0.0, distractor_current]).unwrap();
            if net.compartments[0].is_spiking {
                distractor_spikes += 1;
            }
        }
        assert!(distractor_spikes > 0, "Attractor must survive during distractor injection");

        // 4. Distractor ceases: network must remain persistently active (Need survives distraction)
        let mut post_distractor_spikes = 0;
        for _ in 0..50 {
            net.step(dt, &[0.0, 0.0, 0.0]).unwrap();
            if net.compartments[0].is_spiking {
                post_distractor_spikes += 1;
            }
        }
        assert!(post_distractor_spikes > 0, "Attractor must persist after distractor stops");

        // 5. Actual bodily relief occurs (deficit collapses to 0.0)
        for _ in 0..200 {
            net.need_coupling.update_need(0.0, dt).unwrap();
            net.step(dt, &[0.0, 0.0, 0.0]).unwrap();
        }

        // Attractor collapses cleanly to rest
        assert!(
            (net.compartments[0].voltage() - DEFAULT_LEAK_REVERSAL).abs() < 0.002,
            "Relief must collapse persistent attractor back to rest: got V={}",
            net.compartments[0].voltage()
        );
        assert!(!net.compartments[0].is_spiking);
        assert!(!net.compartments[1].is_spiking);
    }

    #[test]
    fn test_channel_wise_forward_internal_prediction_and_mismatch() {
        let net = create_test_network();

        // Channel 1: Tactile Contact Force [N]
        let mut tactile_pred = ChannelPredictor::new(
            SensoryChannelType::TactileContactForceNewtons,
            0.0, // 0 N baseline
        );
        tactile_pred.add_contact(0, 1.5); // 1.5 N per unit activation of comp 0

        // Channel 2: Retinal Bearing [rad]
        let mut bearing_pred = ChannelPredictor::new(
            SensoryChannelType::RetinalBearingRadians,
            0.25, // 0.25 rad (~14 deg) baseline expectation
        );
        bearing_pred.add_contact(1, 0.10); // +0.10 rad shift with comp 1

        let harness = PersistenceAndPredictionHarness::new(
            net,
            vec![tactile_pred, bearing_pred],
        );

        // 1. Predictions evaluated BEFORE outcome
        let predictions = harness.predict_channels();
        assert_eq!(predictions.len(), 2);
        assert_eq!(predictions[0].0, SensoryChannelType::TactileContactForceNewtons);
        assert_eq!(predictions[1].0, SensoryChannelType::RetinalBearingRadians);

        // 2. Available observation with physical mismatch
        let observations_available = vec![
            (
                SensoryChannelType::TactileContactForceNewtons,
                SensedValue::Available(1.2), // Arriving 1.2 N
            ),
            (
                SensoryChannelType::RetinalBearingRadians,
                SensedValue::Available(0.25), // Arriving 0.25 rad
            ),
        ];

        let results = harness.evaluate_all_mismatches(&predictions, &observations_available);
        assert_eq!(results.len(), 2);

        // Tactile mismatch: 1.2 N - 0.0 N = +1.2 N
        match &results[0].mismatch {
            MismatchResult::Available { error } => {
                assert!((error - 1.2).abs() < 1e-12, "Tactile mismatch must be exact");
            }
            _ => panic!("Expected available mismatch"),
        }

        // Bearing mismatch: 0.25 - 0.25 = 0.0 rad
        match &results[1].mismatch {
            MismatchResult::Available { error } => {
                assert!(error.abs() < 1e-12, "Bearing mismatch must be zero");
            }
            _ => panic!("Expected available mismatch"),
        }

        // 3. Unavailable observation (Out of FOV / sensor occlusion)
        let observations_unavailable = vec![
            (
                SensoryChannelType::TactileContactForceNewtons,
                SensedValue::Unavailable {
                    reason: "Tactile pad not in mechanical contact".to_string(),
                },
            ),
            (
                SensoryChannelType::RetinalBearingRadians,
                SensedValue::Unavailable {
                    reason: "Target outside 50 deg optical field of view".to_string(),
                },
            ),
        ];

        let unavail_results = harness.evaluate_all_mismatches(&predictions, &observations_unavailable);
        match &unavail_results[0].mismatch {
            MismatchResult::Unavailable { reason } => {
                assert!(reason.contains("Tactile pad not in mechanical contact"));
            }
            _ => panic!("Unavailable evidence must not be coerced to numeric reading"),
        }
        match &unavail_results[1].mismatch {
            MismatchResult::Unavailable { reason } => {
                assert!(reason.contains("outside 50 deg optical field of view"));
            }
            _ => panic!("Unavailable optical evidence must remain honestly Unavailable"),
        }
    }

    #[test]
    fn test_c02_targeted_retention_ablation_causality() {
        let mut tactile_pred = ChannelPredictor::new(
            SensoryChannelType::TactileContactForceNewtons,
            0.1, // 0.1 N baseline
        );
        tactile_pred.add_contact(0, 2.0); // Contact 0: +2.0 N
        tactile_pred.add_contact(1, 0.5); // Contact 1: +0.5 N

        let input_acts = vec![1.0, 1.0]; // Both pre-synaptic neurons active

        // Intact prediction
        let intact_pred = tactile_pred.evaluate_prediction(&input_acts);
        assert!((intact_pred - (0.1 + 2.0 + 0.5)).abs() < 1e-12); // 2.6 N

        // Targeted ablation of Contact 0
        tactile_pred.ablate_contact(0).unwrap();
        let ablated_pred = tactile_pred.evaluate_prediction(&input_acts);
        assert!((ablated_pred - (0.1 + 0.5)).abs() < 1e-12); // 0.6 N

        // Confirmation of C02 requirement:
        // Ablating retained physical structure directly alters expectation BEFORE outcome
        assert!(
            (intact_pred - ablated_pred - 2.0).abs() < 1e-12,
            "Prediction delta must exactly equal the ablated synaptic contact capacity"
        );

        // Control check: Contact 1 remains intact
        assert!(!tactile_pred.contacts[1].is_ablated);

        // Restoration check:
        tactile_pred.restore_contact(0).unwrap();
        let restored_pred = tactile_pred.evaluate_prediction(&input_acts);
        assert_eq!(intact_pred, restored_pred);
    }

    #[test]
    fn test_recurrent_continuation_serialization_exactness() {
        let mut net = create_test_network();
        let dt = 0.001;

        // Drive network into active state
        net.need_coupling.update_need(4.0, dt).unwrap();
        for _ in 0..30 {
            net.step(dt, &[0.0, 0.0, 0.0]).unwrap();
        }

        let mut tactile_pred = ChannelPredictor::new(SensoryChannelType::TactileContactForceNewtons, 0.5);
        tactile_pred.add_contact(0, 1.2);
        let predictors = vec![tactile_pred];

        let harness = PersistenceAndPredictionHarness::new(net.clone(), predictors.clone());

        // Serialize active state
        let bytes = harness.serialize_continuation();
        assert!(&bytes[0..8] == CONTINUATION_MAGIC);

        // Restore active state
        let restored = PersistenceAndPredictionHarness::deserialize_continuation(
            &bytes,
            predictors,
            net.gap_junctions.clone(),
            net.recurrent_synapses.clone(),
        ).unwrap();

        // Exact equality check across all compartments
        assert_eq!(harness.network.compartments.len(), restored.network.compartments.len());
        for i in 0..harness.network.compartments.len() {
            let c_orig = &harness.network.compartments[i];
            let c_rest = &restored.network.compartments[i];
            assert_eq!(c_orig.voltage(), c_rest.voltage());
            assert_eq!(c_orig.carrier.remainder, c_rest.carrier.remainder);
            assert_eq!(c_orig.carrier.source_reservoir, c_rest.carrier.source_reservoir);
            assert_eq!(c_orig.carrier.dest_reservoir, c_rest.carrier.dest_reservoir);
        }

        // Stepping both side-by-side must produce bit-exact identical subsequent trajectory
        let mut h1 = harness;
        let mut h2 = restored;
        for _ in 0..20 {
            h1.network.step(dt, &[0.0, 0.0, 0.0]).unwrap();
            h2.network.step(dt, &[0.0, 0.0, 0.0]).unwrap();
        }

        for i in 0..h1.network.compartments.len() {
            assert_eq!(
                h1.network.compartments[i].voltage(),
                h2.network.compartments[i].voltage(),
                "Subsequent step after cold restart must be bit-exact"
            );
        }
    }
