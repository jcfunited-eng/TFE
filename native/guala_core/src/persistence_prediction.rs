#[derive(Debug, Clone, PartialEq)]
pub struct NeuronalCompartment {
    pub id: usize,
    pub carrier: ChargeCarrierState,
    pub leak_conductance: f64,
    pub leak_reversal: f64,
    pub threshold: f64,
    pub reset_voltage: f64,
    pub is_spiking: bool,
}

impl NeuronalCompartment {
    pub fn new(
        id: usize,
        initial_voltage: f64,
        capacitance: f64,
        leak_conductance: f64,
        leak_reversal: f64,
        threshold: f64,
        reset_voltage: f64,
    ) -> Result<Self, ConstitutiveError> {
        if !capacitance.is_finite() || capacitance <= 0.0 {
            return Err(ConstitutiveError::InvalidDomain(
                "capacitance must be strictly positive and finite".to_string(),
            ));
        }
        let q_init = initial_voltage * capacitance;
        // 1 trillion elementary charges per reservoir (plenty for extended repetitive spiking)
        let carrier = ChargeCarrierState::new(q_init, capacitance, 0.0, 1_000_000_000_000, 1_000_000_000_000)?;
        Ok(Self {
            id,
            carrier,
            leak_conductance,
            leak_reversal,
            threshold,
            reset_voltage,
            is_spiking: initial_voltage >= threshold,
        })
    }

    #[inline]
    pub fn voltage(&self) -> f64 {
        self.carrier.voltage()
    }

    #[inline]
    pub fn stored_energy(&self) -> f64 {
        self.carrier.stored_energy()
    }

    /// Advances passive leak current over physical interval dt [s].
    pub fn step_leak(&mut self, dt: f64) -> Result<f64, ConstitutiveError> {
        let v = self.voltage();
        let i_leak = self.leak_conductance * (v - self.leak_reversal);
        let j_c = i_leak * dt;
        let res = self.carrier.settle_transport(j_c, 1, 0.0)?;
        Ok(res.identity_residual)
    }

    /// Applies external or synaptic driving current I_in [A] over dt [s].
    pub fn inject_current(&mut self, current: f64, dt: f64) -> Result<(), ConstitutiveError> {
        if !current.is_finite() {
            return Err(ConstitutiveError::InvalidDomain("current must be finite".to_string()));
        }
        // Inward current depolarizes membrane: Delta Q = +I * dt.
        // settle_transport transfers charge out of source into destination (membrane),
        // so pass -I * dt to increment membrane charge.
        let j_c = -current * dt;
        self.carrier.settle_transport(j_c, 1, 0.0)?;

        // Check action potential threshold
        if self.voltage() >= self.threshold {
            self.is_spiking = true;
            // Physical potassium repolarization: reset voltage to reset_voltage
            let q_reset = self.reset_voltage * self.carrier.c_mem;
            let delta_q_repol = self.carrier.q_membrane - q_reset;
            if delta_q_repol > 0.0 {
                // Outward repolarizing potassium transport
                self.carrier.settle_transport(delta_q_repol, 1, 0.0)?;
            }
        } else {
            self.is_spiking = false;
        }

        Ok(())
    }
}

