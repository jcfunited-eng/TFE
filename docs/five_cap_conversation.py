def transcript_label(s_mode, v_mode, o_mode):
    """Convert mode-ids to a 'word-shaped' utterance label."""
    s = subject_words[s_mode % 3] if s_mode is not None else "?"
    v = verb_words[v_mode % 3] if v_mode is not None else "?"
    o = object_words[o_mode % 3] if o_mode is not None else "?"
    return f"{s} {v} {o}"


