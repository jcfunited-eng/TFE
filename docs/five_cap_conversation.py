def make_projection(n, dim, rng):
    M = rng.standard_normal((n, n)) + 1j * rng.standard_normal((n, n))
    Q, _ = np.linalg.qr(M)
    P = np.zeros((n, n), dtype=complex)
    P[:dim, :dim] = np.eye(dim)
    return Q @ P @ Q.conj().T


def build_system(prefix, sys_rng):
    """Build a system with full 5-capability topology."""
    sections = []
    for sec_name, role in [
        ("subject", "subject_like"),
        ("verb", "verb_like"),
        ("object", "object_like"),
        ("listen", "general"),
        ("speak", "general"),
        ("ground", "grounded"),
        ("intro", "intro"),
    ]:
        s = Section(name=f"{prefix}_{sec_name}", rng=sys_rng, role=role)
        s.map_inject = make_projection(N, 6, sys_rng)
        sections.append(s)
    sys_ = System(sections, sys_rng)
    # Designate intro section
    sys_.intro_section = sys_.sections[f"{prefix}_intro"]
    sys_.intro_krimelack = []
    # Designate grounding section
    sys_.grounding_section = sys_.sections[f"{prefix}_ground"]
    # Keyholes — syntax cascade
    sys_.add_keyhole(f"{prefix}_subject", -2, 8, f"{prefix}_verb", 0.5)
    sys_.add_keyhole(f"{prefix}_verb", -2, 8, f"{prefix}_object", 0.5)
    sys_.add_keyhole(f"{prefix}_object", -2, 8, f"{prefix}_speak", 0.5)
    # Keyholes — conversation loop
    sys_.add_keyhole(f"{prefix}_listen", -2, 8, f"{prefix}_subject", 0.3)
    sys_.add_keyhole(f"{prefix}_speak", -2, 8, f"{prefix}_listen", 0.3)
    return sys_


