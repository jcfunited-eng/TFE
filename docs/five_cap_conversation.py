# Mode purity per section
def mode_purity(commits, true_id_fn):
    mode_to_ids = defaultdict(list)
    for c in commits:
        if c.get("sentence_id") is None:
            continue
        true_id = true_id_fn(c["sentence_id"])
        mode_to_ids[c["mode_id"]].append(true_id)
    purities = []
    for mid, ids in mode_to_ids.items():
        if len(ids) >= 3:
            ctr = Counter(ids)
            purities.append(ctr.most_common(1)[0][1] / len(ids))
    return float(np.mean(purities)) if purities else 0.0, len(mode_to_ids)
